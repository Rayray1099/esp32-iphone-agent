from pathlib import Path
import zlib
ROOT=Path(__file__).resolve().parents[1]
parts=['#pragma once\n// Generated by tools/bundle_web.py; edit web/ sources.\n']
for filename,name in [('index.html','WEB_INDEX'),('app.js','WEB_APP'),('style.css','WEB_STYLE')]:
    text=(ROOT/'web'/filename).read_text(encoding='utf-8')
    parts.append(f'static const char {name}[] = R"WEBASSET({text})WEBASSET";\n')
(ROOT/'hardware/hid_bridge/web_assets.h').write_text(''.join(parts),encoding='utf-8')
print('Bundled local controller assets.')

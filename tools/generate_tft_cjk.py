"""Generate a bounded 1-bit Noto Traditional Chinese font in internal flash.

No font parser, SD card, or runtime allocation is needed on the ESP32.
Source: notofonts/noto-cjk Sans/OTF/TraditionalChinese/NotoSansCJKtc-Regular.otf.
"""
from pathlib import Path
import argparse
import hashlib
from PIL import Image, ImageDraw, ImageFont
from fontTools.ttLib import TTFont

SHA256 = 'dce08bd4fd91aa8aa76ed8fea4b694c2dfb8550f67871e326843212ddbeb88b4'
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('font', type=Path)
parser.add_argument('output', type=Path)
args = parser.parse_args()
assert hashlib.sha256(args.font.read_bytes()).hexdigest() == SHA256, 'Unexpected font source'
cmap = TTFont(args.font).getBestCmap()
# Full unified CJK, extension A, punctuation and full-width Latin forms.
codes = sorted(c for c in cmap if 0x3000 <= c <= 0x303f or 0x3400 <= c <= 0x9fff or 0xff01 <= c <= 0xff60)
font = ImageFont.truetype(str(args.font), 16)
pixels = bytearray()
for code in codes:
    image = Image.new('L', (16, 18))
    ImageDraw.Draw(image).text((0, 15), chr(code), font=font, anchor='ls', fill=255)
    values = list(image.getdata())
    for start in range(0, len(values), 8):
        pixels.append(sum((1 << (7-i)) for i, p in enumerate(values[start:start+8]) if p >= 104))
output = ['// Generated by tools/generate_tft_cjk.py; Noto Sans CJK TC, SIL OFL 1.1.',
          '// Source SHA256: ' + SHA256, '#pragma once', '#include <cstdint>', 'namespace clicker {',
          'inline constexpr uint16_t cjkCodes[] = {']
output += [','.join(str(c) for c in codes[i:i+24])+',' for i in range(0,len(codes),24)]
output += ['};', 'inline constexpr uint8_t cjkPixels[] = {']
output += [','.join(str(p) for p in pixels[i:i+32])+',' for i in range(0,len(pixels),32)]
output += ['};', '} // namespace clicker', '']
args.output.write_text(chr(10).join(output), encoding='utf-8')
print(len(codes), 'glyphs;', len(pixels) + len(codes)*2, 'flash bytes')

"""Generate bounded 4-bit Inter glyphs; no font parser runs on the ESP32."""
from pathlib import Path
import argparse
import hashlib
from PIL import Image, ImageDraw, ImageFont

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('font', type=Path)
parser.add_argument('output', type=Path)
args = parser.parse_args()
assert hashlib.sha256(args.font.read_bytes()).hexdigest() == '29160a80ff49ddcab2c97711247e08b1fab27a484a329ce8b813d820dc559031', 'Unexpected font source'
lines = ['// Generated by tools/generate_tft_font.py. Inter: SIL Open Font License 1.1.',
         '// Source SHA256: 29160a80ff49ddcab2c97711247e08b1fab27a484a329ce8b813d820dc559031',
         '#pragma once', '#include <cstdint>', 'namespace clicker {',
         'struct FontGlyph { uint32_t offset; uint8_t width, height; int8_t x, y; uint8_t advance; };',
         'struct SmoothFont { const FontGlyph *glyphs; const uint8_t *pixels; uint8_t first, last; };']
for size in [11, 14, 18, 26, 58]:
    font = ImageFont.truetype(str(args.font), size)
    font.set_variation_by_axes([32, 600])
    first, last = (32, 126) if size != 58 else (32, 57)
    pixels, glyphs = [], []
    for code in range(first, last + 1):
        char = chr(code)
        x0, y0, x1, y1 = font.getbbox(char, anchor='la')
        width, height = x1 - x0, y1 - y0
        bitmap = Image.new('L', (max(1, width), max(1, height)))
        ImageDraw.Draw(bitmap).text((-x0, -y0), char, font=font, fill=255, anchor='la')
        values = [round(p * 15 / 255) for p in bitmap.getdata()] if width and height else []
        offset = len(pixels)
        if len(values) % 2: values.append(0)
        pixels += [(values[i] << 4) | values[i + 1] for i in range(0, len(values), 2)]
        glyphs.append(f'{{{offset},{width},{height},{x0},{y0},{round(font.getlength(char))}}}')
    lines.append(f'inline constexpr uint8_t font{size}Pixels[] = {{')
    lines += [','.join(str(p) for p in pixels[i:i+32]) + ',' for i in range(0, len(pixels), 32)]
    lines += ['};', f'inline constexpr FontGlyph font{size}Glyphs[] = {{' + ','.join(glyphs) + '};',
              f'inline constexpr SmoothFont font{size} = {{font{size}Glyphs,font{size}Pixels,{first},{last}}};']
lines += ['} // namespace clicker', '']
args.output.write_text(chr(10).join(lines), encoding='utf-8')
print('Generated', args.output, args.output.stat().st_size, 'source bytes')
